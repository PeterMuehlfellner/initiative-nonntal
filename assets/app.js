/* Initiative Erzabt-Klotz-Strasse, page logic.
   No framework, no network calls, no data collection.
   Figures and data come from figures.js (generated by data/build.py). */

(function () {
  "use strict";

  const $ = (sel) => document.querySelector(sel);

  /* -------------------------------------------------- Light / dark ---- */
  const toggle = $("#theme-toggle");
  const stored = (() => {
    try { return localStorage.getItem("theme"); } catch { return null; }
  })();
  if (stored) document.documentElement.dataset.theme = stored;

  if (toggle) {
    toggle.addEventListener("click", () => {
      const root = document.documentElement;
      const isDark = root.dataset.theme
        ? root.dataset.theme === "dark"
        : matchMedia("(prefers-color-scheme: dark)").matches;
      const next = isDark ? "light" : "dark";
      root.dataset.theme = next;
      try { localStorage.setItem("theme", next); } catch { /* never mind */ }
      toggle.setAttribute(
        "aria-label",
        next === "dark" ? "Zu hellem Erscheinungsbild wechseln"
                       : "Zu dunklem Erscheinungsbild wechseln"
      );
    });
  }

  /* --------------------------------------------------- Figures -------- */
  const figures = [
    ["#figure-site", "site"],
    ["#figure-crossings", "crossings"],
    ["#figure-stopping", "stopping"],
  ];
  for (const [sel, key] of figures) {
    const target = $(sel);
    if (target && window.FIGURES && window.FIGURES[key]) {
      target.innerHTML = window.FIGURES[key];
    }
  }

  /* ---------------------------------------- Legend and map markers ---- */
  const legend = $("#legend");
  if (legend && Array.isArray(window.MARKERS)) {
    // The compact variant shows only the short label; the full explanation
    // stays available as a tooltip and to screen readers.
    const compact = legend.classList.contains("legend--compact");
    legend.innerHTML = window.MARKERS
      .map(
        (m) => `<li data-num="${m.num}">
          <button type="button" title="${m.detail.replace(/"/g, "&quot;")}">
            <span class="legend__num f-${m.color}">${m.num}</span>
            <span class="legend__text">${m.short}${
              compact
                ? `<span class="sr-only">. ${m.detail}</span>`
                : `<span class="legend__detail">${m.detail}</span>`
            }</span>
          </button>
        </li>`
      )
      .join("");

    const markers = Array.from(document.querySelectorAll(".marker"));
    const items = Array.from(legend.querySelectorAll("li"));

    const highlight = (num, on) => {
      for (const el of markers) el.classList.toggle("is-active", on && el.dataset.num === String(num));
      for (const li of items) li.classList.toggle("is-active", on && li.dataset.num === String(num));
    };

    for (const li of items) {
      const num = li.dataset.num;
      const button = li.querySelector("button");
      li.addEventListener("mouseenter", () => highlight(num, true));
      li.addEventListener("mouseleave", () => highlight(num, false));
      button.addEventListener("focus", () => highlight(num, true));
      button.addEventListener("blur", () => highlight(num, false));
      // On touch devices a tap highlights and scrolls the map into view
      button.addEventListener("click", () => {
        highlight(num, true);
        const figure = $("#figure-site");
        if (figure && window.matchMedia("(max-width: 949px)").matches) {
          figure.scrollIntoView({ block: "center", behavior: "smooth" });
        }
      });
    }

    for (const el of markers) {
      const num = el.dataset.num;
      el.addEventListener("mouseenter", () => highlight(num, true));
      el.addEventListener("mouseleave", () => highlight(num, false));
      el.addEventListener("focus", () => highlight(num, true));
      el.addEventListener("blur", () => highlight(num, false));
    }
  }

  /* ------------------------------------------- Table of destinations */
  const destBody = document.querySelector("#destinations tbody");
  if (destBody && Array.isArray(window.DESTINATIONS)) {
    destBody.innerHTML = window.DESTINATIONS
      .map(
        (z) =>
          `<tr><td>${z.name}</td><td>${z.kind}</td>` +
          `<td class="num">${z.m} m</td></tr>`
      )
      .join("");
  }

  /* ------------------------------------------------ Letter to the city */
  // MA 1/07 is the competent authority, councillor Schiester heads the
  // planning, transport and climate portfolio, the mayor is copied in.
  const RECIPIENTS = [
    "post@stadt-salzburg.at",
    "stadtraetin.schiester@stadt-salzburg.at",
    "bgm@stadt-salzburg.at",
  ];
  const SUBJECT =
    "Erzabt-Klotz-Straße: Ersuchen um eine Querungsmöglichkeit und Tempo 30";

  const DRAFT = `Sehr geehrte Damen und Herren des Verkehrs- und Straßenrechtsamtes,
sehr geehrte Frau Stadträtin Schiester,
sehr geehrter Herr Bürgermeister Auinger,

als Anrainerin bzw. Anrainer im Nonntal ersuche ich Sie, die Querungssituation in der Erzabt-Klotz-Straße zwischen der Kreuzung Petersbrunnstraße/Akademiestraße und der Nonntaler Hauptstraße zu prüfen.

Auf diesem Abschnitt gibt es genau eine gesicherte Stelle, an der die Fahrbahn überquert werden kann: die Bedarfsampel an der Kreuzung Petersbrunnstraße/Akademiestraße. Südwestlich davon folgen 280 Meter ohne weitere gesicherte Querung, bis die Straße nach der Kurve in die Nonntaler Hauptstraße übergeht. Die beiden Bushaltestellen der Linien 5, 9 und 25 liegen einander in dieser Strecke gegenüber; bis zur Ampel sind es von dort 123 Meter. Ein Seitenwechsel ist für viele unvermeidlich, und gequert wird daher an den Haltestellen, über die gesamte Fahrbahn.

[Hier bitte einen eigenen Satz einfügen: Wie erleben Sie die Stelle? Queren Sie dort selbst, mit Kindern, zu welcher Tageszeit?]

Ich ersuche um Prüfung folgender Maßnahmen:

1. Eine Mittelinsel auf Höhe der Haltestellen. Sie ermöglicht das Queren in zwei Schritten und unterbricht zugleich die durchgehende Fahrbahnfläche, was erfahrungsgemäß geschwindigkeitsdämpfend wirkt. Ein Schutzweg oder eine Bedarfsampel wären gleichwertige Lösungen; es geht um die gesicherte Querung, nicht um eine bestimmte Bauform.

2. Tempo 30 auf diesem Abschnitt. Im Umkreis von 600 Metern liegen sieben Schulen und zwei Kindergärten; die nächste Einrichtung für Kinder ist 124 Meter entfernt. § 43 Abs. 4a StVO in der Fassung seit 1. Juli 2024 sieht für solche Bereiche ausdrücklich vor, dass dafür keine Unfallstatistik und keine Verkehrszählung vorzulegen ist.

3. Eine raschere Grünschaltung der Bedarfsampeln an der Kreuzung Petersbrunnstraße/Akademiestraße, soweit das mit der Signalsteuerung der Obus-Linie vereinbar ist.

Mir ist bewusst, dass eine bauliche Maßnahme die Zustimmung des Landes Salzburg als Straßenerhalter und, wegen der Obus-Anlagen, der Salzburg AG erfordert. Ich ersuche daher auch um Auskunft, welche Stelle das Anliegen weiterverfolgt.

Über eine kurze Rückmeldung zum weiteren Vorgehen würde ich mich freuen.

Mit freundlichen Grüßen


[Ihr Name]
[Ihre Adresse]`;

  const field = $("#draft");
  const mailto = $("#mailto");
  if (field) field.value = DRAFT;

  const buildLink = () => {
    if (!mailto) return;
    const text = field ? field.value : DRAFT;
    mailto.href =
      "mailto:" +
      encodeURIComponent(RECIPIENTS[0]) +
      "?cc=" +
      encodeURIComponent(RECIPIENTS.slice(1).join(",")) +
      "&subject=" +
      encodeURIComponent(SUBJECT) +
      "&body=" +
      encodeURIComponent(text);
  };
  buildLink();
  if (field) field.addEventListener("input", buildLink);

  const copyButton = $("#copy");
  if (copyButton && field) {
    copyButton.addEventListener("click", async () => {
      const original = copyButton.textContent;
      try {
        await navigator.clipboard.writeText(field.value);
        copyButton.textContent = "Kopiert ✓";
      } catch {
        field.select();
        // Mobile devices have no Ctrl+C
        const isTouch = window.matchMedia("(pointer: coarse)").matches;
        copyButton.textContent = isTouch
          ? "Markiert, jetzt „Kopieren“ wählen"
          : "Bitte mit Strg+C kopieren";
      }
      setTimeout(() => { copyButton.textContent = original; }, 2600);
    });
  }
})();
